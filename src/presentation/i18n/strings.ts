export const STRINGS: Readonly<Record<Locale, Dictionary>> = { en, es, pt };

export type TranslateParams = Readonly<Record<string, string | number>>;

/** Looks up a string and fills its {placeholders}. */
export function translate(locale: Locale, key: StringKey, params?: TranslateParams): string {
  const template = STRINGS[locale][key] ?? en[key];
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    params[name] !== undefined ? String(params[name]) : match,
  );
}
